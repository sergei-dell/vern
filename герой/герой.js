/* ═══ 5 · КОНСТРУКТОР ══════════════════════════════════════════════
   Ощущение конструктора держится на трёх вещах: значения стоят с
   первой секунды, предпросмотр меняется на каждый выбор, есть
   «перемешать». Пустых полей не бывает.                            */

function случайныйВыбор() {
  const народ = ключиНародов()[случайное(ключиНародов().length)];
  const н = МИР.народы[народ];
  return {
    народ: народ,
    телосложение: МИР.телосложения[случайное(МИР.телосложения.length)].ключ,
    цвет: н.цвета[случайное(н.цвета.length)].имя,
    отметина: МИР.отметины[случайное(МИР.отметины.length)].ключ,
    имя: '',
    описание: '',
    девиз: случайное(н.девизы.length),
    плащ: МИР.плащи[случайное(МИР.плащи.length)].имя,
    зерно: случайное(НАСТРОЙКИ.зерно.предел)
  };
}

function случайноеИмя(ключНарода) {
  const слоги = МИР.народы[ключНарода].слоги;
  return слоги[случайное(слоги.length)] +
         слоги[случайное(слоги.length)].toLowerCase();
}

function нарисоватьНароды() {
  $('народы').innerHTML = ключиНародов().map((к) => {
    const н = МИР.народы[к];
    // рамка знака красится в цвет своего народа, а не выбранного:
    // иначе все четыре знака выглядят одинаково и выбор не читается
    return '<div class="народ' + (к === выбор.народ ? ' выбран' : '') +
      '" data-народ="' + к + '" style="border-color:' +
      (к === выбор.народ ? н.оттенок : 'transparent') + '">' +
      '<div class="знак" style="border-color:' + н.оттенок + '">' +
      знакНарода(к, НАСТРОЙКИ.знак.поУмолчанию) + '</div>' +
      '<div><b>' + н.имя + '</b><span>' + н.о + '</span></div></div>';
  }).join('');
}

function нарисоватьОблик() {
  const н = МИР.народы[выбор.народ];

  $('телосложения').innerHTML = МИР.телосложения.map((т) =>
    '<div class="вар' + (т.ключ === выбор.телосложение ? ' выбран' : '') +
    '" data-телосложение="' + т.ключ + '">' + т.имя + '</div>').join('');

  $('цвета').innerHTML = н.цвета.map((ц) =>
    '<div class="цвет' + (ц.имя === выбор.цвет ? ' выбран' : '') +
    '" style="background:' + ц.код + '" title="' + ц.имя +
    '" data-цвет="' + ц.имя + '"></div>').join('');

  $('отметины').innerHTML = МИР.отметины.map((о) =>
    '<div class="вар' + (о.ключ === выбор.отметина ? ' выбран' : '') +
    '" data-отметина="' + о.ключ + '">' + о.имя + '</div>').join('');

  $('плащи').innerHTML = МИР.плащи.map((п) =>
    '<div class="цвет' + (п.имя === выбор.плащ ? ' выбран' : '') +
    '" style="background:' + п.код + '" title="' + п.имя +
    '" data-плащ="' + п.имя + '"></div>').join('');
}

function обновитьПревью() {
  const н = МИР.народы[выбор.народ];
  const т = МИР.телосложения.find((э) => э.ключ === выбор.телосложение);
  const о = МИР.отметины.find((э) => э.ключ === выбор.отметина);
  const подпись = подставить(МИР.шаблоны.облик, {
    народ: н.имя.toLowerCase(), телосложение: т.имя,
    цвет: выбор.цвет, отметина: о.имя
  });

  применитьОттенок(выбор.народ);
  ['знак-превью', 'знак-сводка'].forEach((ид) => вставитьЗнак($(ид), выбор.народ));
  $('имя-превью').textContent = выбор.имя || МИР.тексты.безымянный;
  $('имя-сводка').textContent = выбор.имя || МИР.тексты.безымянный;
  $('облик-превью').textContent = подпись;
  $('облик-сводка').textContent = подпись;
}

function перерисоватьВсё() {
  нарисоватьНароды();
  нарисоватьОблик();
  обновитьПревью();
}

function выбратьНарод(ключ) {
  if (ключ === выбор.народ) return;
  выбор.народ = ключ;
  // список цветов свой у каждого народа, поэтому выбор цвета сбрасываем
  выбор.цвет = МИР.народы[ключ].цвета[0].имя;
  выбор.девиз = случайное(МИР.народы[ключ].девизы.length);
  перерисоватьВсё();
}

function перемешать() {
  const было = выбор.имя;
  выбор = случайныйВыбор();
  выбор.имя = было || случайноеИмя(выбор.народ);
  $('поле-имя').value = выбор.имя;
  перерисоватьВсё();
  проверитьИмя();
}

/* ═══ 6 · ИМЯ ══════════════════════════════════════════════════════ */

function ошибкаИмени(значение) {
  const п = НАСТРОЙКИ.имя;
  const т = МИР.тексты;
  if (!значение.length) return '';
  if (значение.length < п.мин) return т.ошибка_коротко;
  if (значение.length > п.макс) return т.ошибка_длинно;
  if (new RegExp(п.цифры).test(значение)) return т.ошибка_цифры;
  if (new RegExp(п.разрешённыеЗнаки).test(значение)) return т.ошибка_знаки;
  if (new RegExp(п.дваПробела).test(значение)) return т.ошибка_пробелы;
  const строчными = значение.toLowerCase();
  if (БРАНЬ.some((слово) => строчными.includes(слово))) return т.ошибка_брань;
  return '';
}

/* Текст, приведённый к виду, в котором его нельзя обойти подменой.

   Убираем всё кроме букв — тогда «н а г а я» и «н.а.г.а.я» сходятся
   с «нагая». Латинские двойники заменяем на русские по таблице из
   брань.js — тогда сходится и «нaгaя» с латинскими «a».

   Цена решения: склеивание слов иногда даёт ложное совпадение на
   стыке. Считаю это меньшим злом, чем пропущенное: человеку достаточно
   переписать фразу, а владельцу отвечать за картинку. */
function сНижнимРегистром(текст) {
  let итог = '';
  for (const знак of текст.toLowerCase()) итог += (ПОДМЕНЫ[знак] || знак);
  return итог;
}

function приведённый(текст) {
  return Array.from(сНижнимРегистром(текст))
    .filter((знак) => /[а-яa-z]/.test(знак))
    .join('');
}

function ошибкаОписания(значение) {
  const т = МИР.тексты;
  if (!значение.length) return '';
  if (значение.length > НАСТРОЙКИ.описание.макс) return т.ошибка_описание_длинно;
  // Две проверки, и обе нужны.
  //
  // Первая — по склеенному тексту, без пробелов и знаков: так ловятся
  // «н а г а я» и «н.а.г.а.я». Годится только для длинных корней.
  //
  // Вторая — по отдельным словам: для коротких и двусмысленных, где
  // корень отбивал бы обычные слова вроде «маски» или «жидкого».
  const чистый = приведённый(значение);
  const покорням = ЗАПРЕЩЕНО_В_ОПИСАНИИ.some((корень) => {
    const к = приведённый(корень);
    return к && чистый.includes(к);
  });
  const слова = сНижнимРегистром(значение).split(/[^а-яa-z]+/);
  const целиком = слова.some((слово) => ЗАПРЕЩЕНО_ЦЕЛИКОМ.includes(слово));
  return (покорням || целиком) ? т.ошибка_описание_запрет : '';
}

function проверитьОписание() {
  const поле = $('поле-описание');
  const значение = поле.value.trim();
  выбор.описание = значение;
  const ошибка = ошибкаОписания(значение);
  $('ошибка-описания').textContent = ошибка;
  $('счёт-описания').textContent = подставить(МИР.шаблоны.счётЗнаков, {
    есть: значение.length, всего: НАСТРОЙКИ.описание.макс
  });
  $('счёт-описания').classList.toggle('много',
    значение.length > НАСТРОЙКИ.описание.макс);
  // дальше не пускаем, пока описание не исправлено
  const кн = document.querySelector('[data-вперёд="3"]');
  if (кн) кн.disabled = !!ошибка;
}

function проверитьИмя() {
  const значение = $('поле-имя').value.trim();
  выбор.имя = значение;
  const ошибка = ошибкаИмени(значение);
  $('ошибка-имени').textContent = ошибка;
  $('к-имя-дальше').disabled = !(значение.length >= НАСТРОЙКИ.имя.мин && !ошибка);
  обновитьПревью();
}

/* ═══ 7 · СБОРКА ФРАЗ ══════════════════════════════════════════════
   Строка судьбы и описание портрета собираются по шаблонам из мир.js.
   Ни одна фраза не написана здесь.                                  */

function подставить(шаблон, значения) {
  // имена подстановок русские, поэтому \w тут не годится: он покрывает
  // только латиницу и цифры, и шаблон оставался бы неразобранным
  return шаблон.replace(/\{([^{}]+)\}/g, (всё, ключ) =>
    (ключ in значения) ? значения[ключ] : всё);
}

function строкаСудьбы(з) {
  const н = МИР.народы[з.народ];
  return подставить(МИР.судьба, {
    народ: н.имя,
    земля: н.земля,
    телосложение: МИР.телосложения.find((э) => э.ключ === з.телосложение).вФразе,
    отметина: МИР.отметины.find((э) => э.ключ === з.отметина).вФразе
  });
}

function описаниеПортрета(з) {
  const н = МИР.народы[з.народ];
  const части = {
    народ: н.англ,
    цвет: н.цвета.find((э) => э.имя === з.цвет).англ,
    телосложение: МИР.телосложения.find((э) => э.ключ === з.телосложение).англ,
    отметина: МИР.отметины.find((э) => э.ключ === з.отметина).англ
  };
  // Порядок жёсткий: каркас, облик, свободный текст, запретный хвост.
  // Хвост обязан быть последним — иначе свободный текст его перебьёт.
  const куски = [
    НАСТРОЙКИ.портрет.каркас,
    подставить(МИР.описаниеПортрета, части),
    безИмени(з.описание, з.имя),
    НАСТРОЙКИ.портрет.хвост
  ];
  // пустая отметина не должна оставлять две запятые подряд
  return куски.filter(Boolean).join(', ')
    .replace(/,\s*,/g, ',').replace(/\s+/g, ' ').trim();
}

/* ═══ 8 · ПОРТРЕТ ══════════════════════════════════════════════════
   Сохраняем сам файл, а не ссылку: сервис однажды поменяет модель, и
   лицо героя изменится. Это ломает главное обещание — герой не
   меняется никогда.                                                 */

/* Имя героя наружу не уходит — так велит ТЗ посредника. Человек мог
   вписать имя в свободное описание, поэтому вычищаем его и оттуда.
   Сравниваем целыми словами: «Ор» не должен съесть «орех».
   Границы слов через \b здесь не годятся — они не знают кириллицы. */
function безИмени(текст, имя) {
  if (!текст || !имя) return текст || '';
  const ч = НАСТРОЙКИ.портрет.чисткаИмени;
  const низ = имя.toLowerCase();
  const склоняется = низ.length >= ч.наименьшаяОснова;

  const этоИмя = (слово) => слово === низ || (склоняется &&
    слово.startsWith(низ) && слово.length - низ.length <= ч.наибольшееОкончание);

  return текст
    .split(/(\s+)/)
    .filter((кусок) => !этоИмя(кусок.replace(/^[^\p{L}]+|[^\p{L}]+$/gu, '').toLowerCase()))
    .join('')
    .replace(/\s+/g, ' ')
    .trim();
}

/* Метка этого браузера. Не опознание человека: случайное число, по
   которому посредник считает портреты по устройствам. Сотрут память
   браузера — метка пропадёт, так и задумано. */
function меткаУстройства() {
  const х = НАСТРОЙКИ.хранение;
  try {
    let метка = localStorage.getItem(х.ключУстройства);
    if (!метка) {
      метка = crypto.randomUUID();
      localStorage.setItem(х.ключУстройства, метка);
    }
    return метка;
  } catch (е) {
    // память закрыта — метка живёт до перезагрузки, счёт держит адрес сети
    return меткаУстройства.разовая ||
      (меткаУстройства.разовая = crypto.randomUUID());
  }
}

/* Картинку храним ФАЙЛОМ, а не ссылкой: посредник когда-нибудь сменит
   модель, и лицо героя изменилось бы. Герой не меняется никогда. */
function вСтроку(кусок) {
  return new Promise((готово, беда) => {
    const чтец = new FileReader();
    чтец.onload = () => готово(чтец.result);
    чтец.onerror = () => беда(чтец.error);
    чтец.readAsDataURL(кусок);
  });
}

/* Просим портрет у посредника. Возвращаем либо картинку, либо код
   беды. Пустой адрес — посредника ещё нет, и это не поломка: герой
   создаётся без портрета и входит в мир. */
async function получитьПортрет(з) {
  const п = НАСТРОЙКИ.портрет;
  if (!п.адрес) return { беда: п.коды.нетПосредника };

  const сторож = new AbortController();
  const будильник = setTimeout(() => сторож.abort(), п.ожиданиеМс);
  try {
    const ответ = await fetch(п.адрес + '?' + new URLSearchParams({ дело: п.дело }), {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        описание: описаниеПортрета(з),
        размер: п.размер,
        зерно: з.зерно,
        устройство: меткаУстройства()
      }),
      signal: сторож.signal
    });
    if (!ответ.ok) {
      const сказано = await ответ.json().catch(() => null);
      return { беда: (сказано && сказано.беда) || п.коды.отказ };
    }
    return { портрет: await вСтроку(await ответ.blob()) };
  } catch (е) {
    return { беда: п.коды.отказ };
  } finally {
    clearTimeout(будильник);
  }
}

function показатьПортрет(з) {
  const место = $('портрет');
  if (з.портрет) {
    const кадр = new Image();
    кадр.src = з.портрет;
    кадр.alt = '';
    место.innerHTML = '';
    место.appendChild(кадр);
    $('к-портрет').hidden = true;
  } else {
    место.innerHTML = '<div class="знак">' +
      знакНарода(з.народ, Math.round(место.clientHeight * НАСТРОЙКИ.знак.доля)) + '</div>';
    $('к-портрет').hidden = попыткиКончились(з);
  }
}

function попыткиКончились(з) {
  return (з.попыток || 0) >= НАСТРОЙКИ.портрет.попытокПредел;
}

async function догнатьПортрет() {
  if (попыткиКончились(герой)) return;
  $('к-портрет').disabled = true;
  $('портрет').innerHTML = '<div class="ждём">' + МИР.тексты.портрет_ждём + '</div>';

  /*  Новое зерно на каждую попытку. Иначе «попробовать ещё раз»
      возвращало бы ту же самую картинку: посредник помнит сделанное
      и на тот же запрос честно отдаёт прежний ответ.               */
  герой.зерно = случайное(НАСТРОЙКИ.зерно.предел);

  const вышло = await получитьПортрет(герой);
  if (вышло.портрет) {
    герой.портрет = вышло.портрет;
    герой.портретСтарый = false;
    герой.попыток = (герой.попыток || 0) + 1;
  }
  сообщитьОПортрете(герой, вышло.беда);
  сохранить(герой);
  показатьПортрет(герой);
  $('к-портрет').disabled = false;
}

/*  Молчаливая пересборка портрета, сделанного до посредника.

    Старые портреты рисовала Sana, её лицензия запрещает коммерцию.
    Пока живых людей нет — это ничего не стоит; когда придут, менять
    будет уже нельзя незаметно. Поэтому меняем сейчас и молча: ни
    сообщения, ни ожидания — вышло, так вышло.                      */
async function обновитьСтарыйПортрет() {
  if (!герой || !герой.портретСтарый || !НАСТРОЙКИ.портрет.адрес) return;
  const вышло = await получитьПортрет(герой);
  if (!вышло.портрет) return;             // не вышло — старый пока остаётся
  герой.портрет = вышло.портрет;          // прежний стёрт вместе с заменой
  герой.портретСтарый = false;
  сохранить(герой);
  показатьПортрет(герой);
}

/* Что написать под героем после попытки получить портрет. */
/*  Посредник называет беду КОДОМ, а не словами: все человеческие
    тексты живут в `мир.js`, и на сервере им делать нечего. Здесь код
    превращается в надпись. Незнакомый код — общая надпись.         */
function сообщитьОПортрете(з, беда) {
  const т = МИР.тексты;
  if (з.портрет && !беда) {
    $('сообщение').textContent = попыткиКончились(з) ? т.портрет_попытки : '';
    return;
  }
  $('сообщение').textContent =
    т[НАСТРОЙКИ.портрет.коды.приставка + беда] || т.портрет_нет;
}

/* ═══ 9 · ХРАНЕНИЕ ═════════════════════════════════════════════════ */

/*  Цвета фигурки. Кожа выбирается человеком в шаге облика, волосы
    задаёт народ, плащ выбирается отдельно. Если чего-то нет — берём
    первое из списка, чтобы фигурка нарисовалась в любом случае.   */

function цветКожи(з) {
  const цвета = МИР.народы[з.народ].цвета;
  return (цвета.find((ц) => ц.имя === з.цвет) || цвета[0]).код;
}

function цветПлаща(з) {
  return (МИР.плащи.find((п) => п.имя === з.плащ) || МИР.плащи[0]).код;
}

function сохранить(запись) {
  try {
    localStorage.setItem(НАСТРОЙКИ.хранение.ключ, JSON.stringify(запись));
    return true;
  } catch (е) {
    return false;             // память браузера переполнена — герой уже на экране
  }
}

function достать() {
  try {
    const строка = localStorage.getItem(НАСТРОЙКИ.хранение.ключ);
    if (!строка) return null;
    const запись = JSON.parse(строка);
    // народ мог исчезнуть из мир.js — тогда запись считаем негодной
    return (запись && МИР.народы[запись.народ]) ? перевести(запись) : null;
  } catch (е) {
    return null;
  }
}

/*  Перевод записи на нынешнее устройство.

    Портреты старее второй версии рисовала Sana — её лицензия
    запрещает коммерцию. Такой портрет помечается и при первом же
    входе молча заменяется новым, сделанным через посредника.
    Счётчик попыток при этом обнуляется: человек ни в чём не виноват
    и не должен из-за нашего переезда остаться без портрета.        */
function перевести(запись) {
  const надо = НАСТРОЙКИ.хранение.версияЗаписи;
  if ((запись.версия || 1) >= надо) return запись;
  if (запись.портрет) {
    запись.портретСтарый = true;
    запись.попыток = 0;
  }

  /*  Трёх цветов фигурки в старых записях не было — они появились
      вместе с картой. Достаём их из того, что человек уже выбрал:
      кожу из облика, волосы из народа. Плащ он не выбирал никогда,
      поэтому берём по зерну — у каждого героя своё, и цвета выйдут
      разные, а не один на всех.                                   */
  if (!запись.цветКожи) {
    if (!запись.плащ) {
      запись.плащ = МИР.плащи[(запись.зерно || 0) % МИР.плащи.length].имя;
    }
    запись.цветПлаща = цветПлаща(запись);
    запись.цветКожи  = цветКожи(запись);
    запись.цветВолос = МИР.народы[запись.народ].волосы;
  }

  запись.версия = надо;
  сохранить(запись);
  return запись;
}

function стереть() {
  try { localStorage.removeItem(НАСТРОЙКИ.хранение.ключ); } catch (е) {}
}

