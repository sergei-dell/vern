function запуск() {
  расставитьТексты();

  $('полоска').innerHTML = '<i></i>'.repeat(НАСТРОЙКИ.шагов);
  $('поле-имя').maxLength = НАСТРОЙКИ.имя.макс;
  $('поле-имя').placeholder = МИР.тексты.поле_имя;
  $('поле-описание').maxLength = НАСТРОЙКИ.описание.макс;
  $('поле-описание').placeholder = МИР.тексты.поле_описание;

  выбор = случайныйВыбор();
  повеситьСобытия();
  проверитьОписание();          // счётчик знаков виден с самого начала

  герой = достать();
  if (герой) обновитьСтарыйПортрет();    // без ожидания: экран покажут отдельно
}

