/* ═══ 3 · МЕЛОЧИ ═══════════════════════════════════════════════════ */

const случайное = (сколько) => Math.floor(Math.random() * сколько);
const ключиНародов = () => Object.keys(МИР.народы);

function знакНарода(ключ, размер) {
  const н = МИР.народы[ключ];
  return '<svg xmlns="' + НАСТРОЙКИ.знак.пространствоИмён +
    '" width="' + размер + '" height="' + размер +
    '" viewBox="' + НАСТРОЙКИ.знак.холст + '" fill="none" stroke="' + н.оттенок +
    '" stroke-width="' + НАСТРОЙКИ.знак.толщинаЛинии +
    '" stroke-linejoin="round">' + н.знак + '</svg>';
}

/* Размеры знака заданы в css через переменные бокса, а сам svg рисуется
   от размера своего места — берём его из вычисленного стиля. */
function вставитьЗнак(узел, ключ) {
  const сторона = Math.round(узел.clientWidth * НАСТРОЙКИ.знак.доля)
    || НАСТРОЙКИ.знак.поУмолчанию;
  узел.innerHTML = знакНарода(ключ, сторона);
}

