let выбор = null;
let герой = null;
let шаг = 0;

/* ═══ 1 · ТЕМА ═════════════════════════════════════════════════════
   Цвета берём у Телеграма. Вне его — запасные из настроек, чтобы
   страница открывалась в обычном браузере для разработки.          */

const СООТВЕТСТВИЕ_ТЕМЫ = {
  bg_color: '--фон',
  secondary_bg_color: '--поле',
  text_color: '--текст',
  hint_color: '--тусклый',
  button_color: '--кнопка',
  button_text_color: '--текст-кнопки',
  destructive_text_color: '--тревога'
};

function применитьТему() {
  const тема = Object.assign(
    {}, НАСТРОЙКИ.запаснаяТема,
    (тг && тг.themeParams) ? тг.themeParams : {}
  );
  for (const [откуда, куда] of Object.entries(СООТВЕТСТВИЕ_ТЕМЫ)) {
    if (тема[откуда]) document.documentElement.style.setProperty(куда, тема[откуда]);
  }
}

function применитьОттенок(ключНарода) {
  document.documentElement.style.setProperty(
    '--оттенок', МИР.народы[ключНарода].оттенок);
}

