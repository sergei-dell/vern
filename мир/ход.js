function показатьЛавку() {
  const м = местоПо(где.место);
  const л = м.лавка;
  const т = МИР.тексты;
  const х = обитатель(л.хозяин);

  $('имя-лавки').textContent = л.название;
  $('хозяин-лавки').innerHTML = знакНарода(х.народ, НАСТРОЙКИ.знак.уОбитателя) +
    '<span>' + х.имя + '</span>';
  $('описание-лавки').textContent = л.описание;

  const естьСтолы = !л.закрыта && л.столы.length > 0;
  $('заголовок-столов').hidden = !естьСтолы;
  $('столы-лавки').hidden = !естьСтолы;
  $('лавка-примечание').textContent = л.закрыта ? т.лавка_закрыта
    : (л.столы.length ? '' : т.лавка_без_столов);

  if (естьСтолы) $('столы-лавки').innerHTML = л.столы.map((стол) => {
    const занято = занятоЗа(м.ключ, стол);
    const полон = занято >= стол.мест;
    const мойНомер = мироеСостояние.очереди[ключСтола(м.ключ, стол.ключ)];
    const сижу = мироеСостояние.посадки[ключСтола(м.ключ, стол.ключ)] !== undefined;

    const лица = [];
    for (let i = 0; i < стол.мест; i++) {
      const кто = ктоСидит(м.ключ, стол, i);
      if (!кто) continue;
      лица.push(кто.ты ? '<span>' + т.стол_ты + '</span>'
        : знакНарода(кто.обитатель.народ, НАСТРОЙКИ.знак.уОбитателя) +
          '<span>' + кто.обитатель.имя + '</span>');
    }

    // Кнопка обязана говорить правду. Полон и ты не в очереди — можно
    // встать в очередь. Уже в очереди — сесть нельзя, но посмотреть на
    // стол можно. Есть свободное место — садись.
    let подписьКнопки = т.стол_сесть;
    if (полон && !сижу) подписьКнопки = (мойНомер === undefined)
      ? т.стол_очередь : т.стол_смотреть;

    return '<div class="стол-строка">' +
      '<div class="о-столе"><b>' + стол.имя + '</b>' +
      '<div class="кто">' + подставить(т.занято_из, { есть: занято, всего: стол.мест }) +
      (лица.length ? ' · ' + лица.join(' ') : '') + '</div>' +
      '<div class="ставка">' + (стол.ставка > 0
        ? подставить(т.стол_ставка, { сколько: стол.ставка }) : т.стол_бесплатно) +
      (мойНомер !== undefined
        ? ' · ' + подставить(т.стол_вочереди, { номер: мойНомер }) : '') +
      '</div></div>' +
      '<button class="кн мелкая ' + (полон && !сижу ? 'тихая' : 'главная') +
      '" data-стол="' + стол.ключ + '">' + подписьКнопки + '</button></div>';
  }).join('');

  показатьЭкран('э-лавка');
}

