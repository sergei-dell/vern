/* Кто сидит на месте за столом: заготовленный обитатель, ты или никто. */
function ктоСидит(местоКлюч, стол, номерМеста) {
  const моё = мироеСостояние.посадки[ключСтола(местоКлюч, стол.ключ)];
  if (моё === номерМеста) return { ты: true };
  const ключ = стол.сидят[номерМеста];
  return ключ ? { обитатель: обитатель(ключ), ключ: ключ } : null;
}

function занятоЗа(местоКлюч, стол) {
  let сколько = 0;
  for (let i = 0; i < стол.мест; i++) if (ктоСидит(местоКлюч, стол, i)) сколько++;
  return сколько;
}

/* Строка занятости на карточке лавки — главный сигнал для человека. */
function занятостьЛавки(место) {
  const т = МИР.тексты;
  const л = место.лавка;
  if (л.закрыта) return т.занято_закрыто;
  if (!л.столы.length) return т.занято_витрина;
  let занято = 0, всего = 0, вОчереди = 0;
  for (const стол of л.столы) {
    занято += занятоЗа(место.ключ, стол);
    всего += стол.мест;
    вОчереди += стол.очередь;
  }
  if (занято === 0) return т.занято_пусто;
  if (занято >= всего && вОчереди > 0)
    return подставить(т.занято_очередь, { сколько: вОчереди });
  return подставить(т.занято_из, { есть: занято, всего: всего });
}

