function показатьСтраницу(ключСтраницы, ключКвартала) {
  const с = страницаПо(ключСтраницы);
  где.страница = с.ключ;
  где.квартал = ключКвартала || где.квартал || МИР.кварталы.find((к) => к.доступен).ключ;

  // вид кольца вешается на тело: правила лежат в страницы.css
  document.body.className = с.вид;
  $('имя-страницы').textContent = с.имя;

  const открытые = открытыеСтраницы();
  const номер = открытые.findIndex((э) => э.ключ === с.ключ);
  $('к-предыдущая').disabled = (номер <= 0);
  $('к-следующая').disabled = (номер >= открытые.length - 1);

  нарисоватьКарту();
  нарисоватьТочки();
  показатьЭкран('э-страница');
}

function перелистнуть(куда) {
  const открытые = открытыеСтраницы();
  const номер = открытые.findIndex((э) => э.ключ === где.страница);
  const новый = номер + куда;
  if (новый < 0 || новый >= открытые.length) return;
  показатьСтраницу(открытые[новый].ключ, где.квартал);
}

/* Листание пальцем. Кнопки-стрелки при этом обязательны и работают
   всегда: на слабых телефонах жест срывается, и без кнопок человек
   застревает на одной странице. */
function повеситьЛистание() {
  let началоX = 0, началоY = 0, следим = false;
  const узел = $('э-страница');
  узел.addEventListener('touchstart', (с) => {
    началоX = с.touches[0].clientX;
    началоY = с.touches[0].clientY;
    следим = true;
  }, { passive: true });
  узел.addEventListener('touchend', (с) => {
    if (!следим) return;
    следим = false;
    const сдвигX = с.changedTouches[0].clientX - началоX;
    const сдвигY = с.changedTouches[0].clientY - началоY;
    if (Math.abs(сдвигY) > НАСТРОЙКИ.листание.порогОтклонения) return;
    if (Math.abs(сдвигX) < НАСТРОЙКИ.листание.порогПальца) return;
    перелистнуть(сдвигX < 0 ? 1 : -1);
  }, { passive: true });
}

