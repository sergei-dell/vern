function повеситьСобытия() {
  $('к-войти').addEventListener('click', () => {
    показатьСтраницу(открытыеСтраницы()[0].ключ, null);
  });

  $('к-предыдущая').addEventListener('click', () => перелистнуть(-1));
  $('к-следующая').addEventListener('click', () => перелистнуть(1));

  $('карта').addEventListener('click', (с) => {
    const узел = с.target.closest('[data-место]');
    if (узел) открытьМесто(узел.dataset.место);
  });

  $('к-из-лавки').addEventListener('click', () =>
    показатьСтраницу(где.страница, где.квартал));

  $('столы-лавки').addEventListener('click', (с) => {
    const узел = с.target.closest('[data-стол]');
    if (!узел) return;
    const м = местоПо(где.место);
    const стол = м.лавка.столы.find((э) => э.ключ === узел.dataset.стол);
    const полон = занятоЗа(м.ключ, стол) >= стол.мест;
    const ключ = ключСтола(м.ключ, стол.ключ);
    const сижу = мироеСостояние.посадки[ключ] !== undefined;
    const вОчереди = мироеСостояние.очереди[ключ] !== undefined;
    if (полон && !сижу && !вОчереди) { встатьВОчередь(стол); return; }
    войтиЗаСтол(стол.ключ);
  });

  $('к-из-стола').addEventListener('click', показатьЛавку);

  $('круг-стола').addEventListener('click', (с) => {
    const узел = с.target.closest('[data-сесть]');
    if (узел) сесть(Number(узел.dataset.сесть));
  });

  $('к-сказать').addEventListener('click', сказать);
  $('поле-чата').addEventListener('keydown', (с) => {
    if (с.key === 'Enter') сказать();
  });

  $('завеса').addEventListener('click', (с) => {
    if (с.target === $('завеса')) закрытьОкошко();
  });
}

