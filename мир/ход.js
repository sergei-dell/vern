/* Состояние ларька решается тем, что в нём происходит, а не вкусом:
   закрыт — приглушён, есть занятые места — людно, иначе просто открыт. */
function состояниеМеста(м) {
  if (!м.лавка) return 'свободно';
  if (м.лавка.закрыта) return 'закрыта';
  const занято = м.лавка.столы.reduce(
    (сумма, стол) => сумма + занятоЗа(м.ключ, стол), 0);
  return занято > 0 ? 'людно' : 'открыта';
}

function фигура(имя, размер) {
  return '<svg class="силуэт" viewBox="0 0 48 48" width="' + размер +
    '" height="' + размер + '" aria-hidden="true"><use href="#' + имя +
    '"/></svg>';
}

function дорожки(раскладка) {
  const линии = раскладка.дорожки.map((д) =>
    '<path vector-effect="non-scaling-stroke" d="M' + раскладка.сердце.x +
    ' ' + раскладка.сердце.y + ' Q' + д.изгиб.x + ' ' + д.изгиб.y + ' ' +
    д.к.x + ' ' + д.к.y + '"/>'
  ).join('');
  /* viewBox в долях — удобно для координат, но у толщины линии те же
     единицы: 2.5 доли это восемьсот точек, и три дорожки заливали всю
     карту золотом. Спасает vector-effect, и ставить его надо на каждой
     линии: по наследству он не передаётся. */
  return '<svg class="дорожки" viewBox="0 0 1 1" preserveAspectRatio="none"' +
    ' aria-hidden="true"><g fill="none" stroke-linecap="round">' +
    линии + '</g></svg>';
}

/* Проверяем, что пальцем попадёшь: центры не должны сходиться ближе
   заданного. Ругаемся в консоль, а не молчим — иначе ошибку раскладки
   заметишь только по жалобам. */
function проверитьРазброс(места, ширина, высота) {
  for (let i = 0; i < места.length; i++) {
    for (let j = i + 1; j < места.length; j++) {
      const a = места[i].где, b = места[j].где;
      const далеко = Math.hypot((a.x - b.x) * ширина, (a.y - b.y) * высота);
      if (далеко < НАСТРОЙКИ.карта.минРасстояние) {
        console.warn('карта', места[i].ключ, места[j].ключ, Math.round(далеко));
      }
    }
  }
}

function нарисоватьКарту() {
  const с = страницаПо(где.страница);
  const карта = $('карта');
  const р = с.карта;
  if (!р) { карта.innerHTML = ''; return; }

  const к = НАСТРОЙКИ.карта;
  const места = МИР.места.filter((м) => м.страница === с.ключ && м.где);
  const куски = [дорожки(р)];

  for (const п of р.подписи) {
    const кв = МИР.кварталы.find((э) => э.ключ === п.квартал);
    куски.push('<div class="подпись-квартала" style="--х:' + п.x +
      ';--у:' + п.y + '">' + кв.имя + '</div>');
  }

  куски.push('<div class="сердце" style="--х:' + р.сердце.x + ';--у:' +
    р.сердце.y + ';--доля:' + к.сердцеДоля + '">' +
    фигура('силуэт-сердце', НАСТРОЙКИ.знак.вКарточке) +
    '<span class="имя">' + МИР.тексты.сердце + '</span></div>');

  for (const м of места) {
    const состояние = состояниеМеста(м);
    const кв = МИР.кварталы.find((э) => э.ключ === м.квартал);
    const силуэт = м.лавка ? кв.силуэт : 'силуэт-свободно';
    const имя = м.лавка ? м.лавка.название
      : подставить(МИР.тексты.место_цена, { цена: м.цена });
    куски.push('<div class="ларёк ' + состояние + '" data-место="' + м.ключ +
      '" style="--х:' + м.где.x + ';--у:' + м.где.y + ';--доля:' +
      к.ларёкДоля + '">' + фигура(силуэт, НАСТРОЙКИ.знак.вКарточке) +
      '<span class="имя">' + имя + '</span></div>');
  }

  карта.innerHTML = куски.join('');
  проверитьРазброс(места, карта.clientWidth,
                   карта.clientWidth * к.высотаКШирине);
}

