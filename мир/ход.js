/* Тему мессенджера мир НЕ слушает — почему, написано в настройки.js.
   Наоборот: сообщаем Телеграму свой фон, чтобы его полоска сверху не
   спорила с картой. Если метода нет, ничего страшного не случится. */
function применитьТему() {
  const цвета = НАСТРОЙКИ.цвета;
  for (const [откуда, куда] of Object.entries(СООТВЕТСТВИЕ_ТЕМЫ)) {
    document.documentElement.style.setProperty(куда, цвета[откуда]);
  }
  if (!тг) return;
  try {
    if (тг.setBackgroundColor) тг.setBackgroundColor(цвета.bg_color);
    if (тг.setHeaderColor) тг.setHeaderColor(цвета.bg_color);
  } catch (е) { /* старая оболочка — переживём */ }
}

function расставитьТексты() {
  document.querySelectorAll('[data-т]').forEach((узел) => {
    узел.textContent = МИР.тексты[узел.dataset.т];
  });
}

function подставить(шаблон, значения) {
  // имена подстановок русские, поэтому \w здесь не годится
  return шаблон.replace(/\{([^{}]+)\}/g, (всё, ключ) =>
    (ключ in значения) ? значения[ключ] : всё);
}

