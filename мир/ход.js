function нарисоватьКруг() {
  const м = местоПо(где.место);
  const стол = столСейчас();
  const т = МИР.тексты;
  const н = НАСТРОЙКИ.стол;
  const круг = $('круг-стола');

  let разметка = '<div class="середина">' + стол.имя + '</div>';
  for (let i = 0; i < стол.мест; i++) {
    const кто = ктоСидит(м.ключ, стол, i);
    const угол = (н.уголНачалаДоля + i / стол.мест) * Math.PI * 2;
    const x = н.середина + Math.cos(угол) * н.радиусДоля;
    const y = н.середина + Math.sin(угол) * н.радиусДоля;
    const ходит = ходитЛи(i);

    let нутро, классы = ['место-за-столом'];
    if (ходит) классы.push('ходит');
    if (кто && кто.ты) {
      нутро = (герой && герой.портрет)
        ? '<img src="' + герой.портрет + '" alt="">'
        : знакНарода(герой ? герой.народ : стол.сидят[i], НАСТРОЙКИ.знак.вКарточке);
      разметка += подпись(классы, x, y, н, нутро, герой ? герой.имя : т.стол_ты);
    } else if (кто) {
      нутро = знакНарода(кто.обитатель.народ, НАСТРОЙКИ.знак.вКарточке);
      разметка += подпись(классы, x, y, н, нутро, кто.обитатель.имя);
    } else {
      классы.push('пустое');
      разметка += подпись(классы, x, y, н, '', т.стол_свободно, i);
    }
  }
  круг.innerHTML = разметка;

  function подпись(классы, x, y, н, нутро, текст, свободное) {
    return '<div class="' + классы.join(' ') + '" style="--х:' + x + ';--у:' + y +
      ';--размер:' + н.местоДоля + '"' +
      (свободное !== undefined ? ' data-сесть="' + свободное + '"' : '') + '>' +
      '<div class="лицо">' + нутро + '</div>' +
      '<div class="подпись">' + текст + '</div></div>';
  }
}

/* Чей сейчас ход. Для шахмат спрашиваем у доски, для прочих механик
   хода нет — их правила появятся позже. */
function ходитЛи(номерМеста) {
  const стол = столСейчас();
  if (стол.механика !== МИР.механики.шахматы || !window.ШАХМАТЫ) return false;
  return window.ШАХМАТЫ.чейХод() === номерМеста;
}

/* Доска и её библиотека грузятся только когда человек сел за стол.
   На карте они не нужны, а весят больше всего остального вместе.
   Не загрузилось — это и есть тот самый обрыв связи. */
async function подключитьШахматы() {
  if (window.ШАХМАТЫ) return true;
  try {
    await import('./шахматы.js');
    return !!window.ШАХМАТЫ;
  } catch (е) {
    return false;
  }
}

async function показатьСтол() {
  const стол = столСейчас();
  const т = МИР.тексты;
  $('имя-стола').textContent = стол.имя;
  нарисоватьКруг();
  нарисоватьРазговор();

  const поле = $('поле-игры');
  поле.innerHTML = '';
  $('стол-примечание').textContent = '';
  обновитьХод();
  показатьЭкран('э-стол');

  if (стол.механика !== МИР.механики.шахматы) {
    $('стол-примечание').textContent = т.стол_механика_позже;
    return;
  }

  $('стол-примечание').textContent = т.доска_грузится;
  const вышло = await подключитьШахматы();
  // пока грузилось, человек мог уйти к другому столу
  if (столСейчас() !== стол) return;
  if (!вышло) {
    $('стол-примечание').textContent = '';
    окошко(т.связь_пропала, т.ошибка_загрузки,
      [[т.связь_ещё_раз, () => location.reload(), true]]);
    return;
  }
  const м = местоПо(где.место);
  window.ШАХМАТЫ.поставить(поле, обновитьХод, ключСтола(м.ключ, стол.ключ));
  $('стол-примечание').textContent = т.шахматы_за_обоих;
  обновитьХод();
}

/* Зовётся доской после каждого хода: обновляет подпись и обводку. */
function обновитьХод() {
  const стол = столСейчас();
  const т = МИР.тексты;
  if (стол.механика !== МИР.механики.шахматы || !window.ШАХМАТЫ) {
    $('чей-ход').textContent = '';
    return;
  }
  const сторона = window.ШАХМАТЫ.чейХод() === 0 ? т.шахматы_белые : т.шахматы_чёрные;
  $('чей-ход').textContent = подставить(т.стол_ход, { кто: сторона });
  нарисоватьКруг();
}

function сесть(номерМеста) {
  const м = местоПо(где.место);
  const стол = столСейчас();
  мироеСостояние.посадки[ключСтола(м.ключ, стол.ключ)] = номерМеста;
  delete мироеСостояние.очереди[ключСтола(м.ключ, стол.ключ)];
  сохранитьСостояние();
  нарисоватьКруг();
}

function встатьВОчередь(стол) {
  const м = местоПо(где.место);
  const ключ = ключСтола(м.ключ, стол.ключ);
  if (мироеСостояние.очереди[ключ] === undefined)
    мироеСостояние.очереди[ключ] = стол.очередь + 1;
  сохранитьСостояние();
  показатьЛавку();
}

/* ═══ 8 · РАЗГОВОР ═════════════════════════════════════════════════
   Заготовленный. Отправка работает только у тебя — общего мира нет. */

function нарисоватьРазговор() {
  const м = местоПо(где.место);
  const ключ = ключСтола(м.ключ, где.стол);
  const мои = мироеСостояние.разговоры[ключ] || [];
  const все = МИР.разговор.map((р) => ({
    имя: обитатель(р.кто).имя, что: р.что, моя: false
  })).concat(мои.map((что) => ({
    имя: герой ? герой.имя : МИР.тексты.стол_ты, что: что, моя: true
  })));

  $('разговор').innerHTML = все.map((р) =>
    '<div class="реплика' + (р.моя ? ' моя' : '') + '"><b>' + р.имя +
    '</b> ' + р.что + '</div>').join('');
  $('разговор').scrollTop = $('разговор').scrollHeight;
}

function сказать() {
  const поле = $('поле-чата');
  const что = поле.value.trim();
  if (!что) return;
  const м = местоПо(где.место);
  const ключ = ключСтола(м.ключ, где.стол);
  if (!мироеСостояние.разговоры[ключ]) мироеСостояние.разговоры[ключ] = [];
  мироеСостояние.разговоры[ключ].push(что);
  поле.value = '';
  сохранитьСостояние();
  нарисоватьРазговор();
}

